import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip";
import { cn } from "@/lib/utils";

type Kind =
  | "real"
  | "synthetic"
  | "forecast"
  | "mock"
  | "assumed"
  | "measured"
  | "synthetic_and_real"
  | "user_adjusted"
  | "live";

const STYLES: Record<Kind, string> = {
  real: "border-success/30 bg-success/10 text-success",
  live: "border-success/30 bg-success/10 text-success",
  measured: "border-success/30 bg-success/10 text-success",
  synthetic: "border-warning/30 bg-warning/10 text-warning",
  synthetic_and_real: "border-warning/30 bg-warning/10 text-warning",
  mock: "border-warning/30 bg-warning/10 text-warning",
  forecast: "border-primary/25 bg-accent text-accent-foreground",
  assumed: "border-border bg-muted text-muted-foreground",
  user_adjusted: "border-border bg-muted text-muted-foreground",
};

const LABELS: Record<Kind, string> = {
  real: "Gateway traffic",
  live: "Live provider",
  measured: "Measured",
  synthetic: "Synthetic demo data",
  synthetic_and_real: "Synthetic history + gateway traffic",
  mock: "Mock provider",
  forecast: "Forecast",
  assumed: "Assumed",
  user_adjusted: "Your assumption",
};

const HELP: Record<Kind, string> = {
  real: "Requests that passed through the TokenGuard gateway, including mock-provider requests. Check the provider badge for real Anthropic calls.",
  live: "Real Anthropic API calls.",
  measured: "Computed from observed gateway traffic.",
  synthetic: "Generated by the seeded simulator (seed 42). Not real customer data.",
  synthetic_and_real: "Seeded synthetic history plus any live gateway traffic; shares are shown where it matters.",
  mock: "Mock mode: no Anthropic call was made; token counts are estimates.",
  forecast: "Model prediction, not an observation.",
  assumed: "An assumption, not a measurement. Adjust it to see the sensitivity.",
  user_adjusted: "Adjusted by you in the Decision Lab.",
};

export function DataSourceBadge({ origin, className }: { origin: string; className?: string }) {
  const kind = (origin in STYLES ? origin : "assumed") as Kind;
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span
          tabIndex={0}
          className={cn(
            "inline-flex cursor-help items-center whitespace-nowrap rounded-full border px-2 py-0.5 text-[11px] font-semibold",
            STYLES[kind],
            className,
          )}
        >
          {LABELS[kind]}
        </span>
      </TooltipTrigger>
      <TooltipContent className="max-w-64">{HELP[kind]}</TooltipContent>
    </Tooltip>
  );
}
