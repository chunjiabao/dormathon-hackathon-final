import { ArrowRight, CircleCheck, CircleSlash, Lightbulb } from "lucide-react";
import Link from "next/link";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import type { Recommendation } from "@/lib/types";

const STATUS: Record<Recommendation["status"], string> = {
  proposed: "Awaiting owner decision",
  approved: "Approved",
  enabled: "Approved & enabled",
  rejected: "Rejected",
  disabled: "Disabled after enablement",
};

export function RecommendationCard({
  rec,
  showLink = true,
}: {
  rec: Pick<Recommendation, "action_type" | "status" | "rationale" | "superseded"> | null;
  showLink?: boolean;
}) {
  return (
    <Card className="gap-3 shadow-[var(--shadow-soft)]">
      <CardHeader className="pb-0">
        <CardTitle className="flex items-center gap-2 text-[15px]">
          <Lightbulb className="size-4 text-primary" aria-hidden /> Recommended action
        </CardTitle>
      </CardHeader>
      <CardContent className="space-y-3">
        {!rec ? (
          <p className="text-sm text-muted-foreground">
            No recommendation yet. Generate one in the Decision Lab after a forecast has run.
          </p>
        ) : (
          <>
            <div className="flex flex-wrap items-center gap-2">
              {rec.action_type === "enable_semantic_cache" ? (
                <span className="flex items-center gap-1.5 font-semibold">
                  <CircleCheck className="size-4 text-success" aria-hidden /> Enable approved-FAQ caching
                </span>
              ) : (
                <span className="flex items-center gap-1.5 font-semibold">
                  <CircleSlash className="size-4 text-muted-foreground" aria-hidden /> No safe intervention yet
                </span>
              )}
              <Badge variant="secondary">{STATUS[rec.status]}</Badge>
              {rec.superseded && <Badge variant="outline">Older forecast</Badge>}
            </div>
            <p className="text-[13px] leading-relaxed text-muted-foreground">{rec.rationale}</p>
            <p className="text-xs text-muted-foreground">
              Generated by deterministic rules from the forecast and simulation. No LLM was used for this recommendation.
            </p>
          </>
        )}
        {showLink && (
          <Button asChild variant="outline" size="sm">
            <Link href="/decisions">
              Open Decision Lab <ArrowRight className="size-3.5" />
            </Link>
          </Button>
        )}
      </CardContent>
    </Card>
  );
}
